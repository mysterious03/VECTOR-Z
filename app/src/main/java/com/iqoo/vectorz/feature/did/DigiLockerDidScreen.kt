                    Text(text = "Disclose 12-Digit Aadhaar (Masked: •••• 7819)", color = Color.White, fontSize = 12.sp)
                }
            }
        }

        Spacer(modifier = Modifier.height(16.dp))

        Button(
            onClick = { zkProofGenerated = true },
            colors = ButtonDefaults.buttonColors(containerColor = Color(0xFF00B0FF)),
