    var isOver18Disclosed by remember { mutableStateOf(true) }
    var isFullNameDisclosed by remember { mutableStateOf(true) }
    var isAadhaarDisclosed by remember { mutableStateOf(false) }
    var zkProofGenerated by remember { mutableStateOf(false) }

    Column(
        modifier = modifier
            .fillMaxSize()
            .background(VectorZBlack)
            .padding(16.dp)
    ) {
        // Top Header
        Row(
            modifier = Modifier.fillMaxWidth(),
            verticalAlignment = Alignment.CenterVertically
        ) {
            Text(
                text = "←",
                fontSize = 24.sp,
                color = Color.White,
                modifier = Modifier.clickable { onBack() }
            )
            Spacer(modifier = Modifier.width(12.dp))
            Column {
                Text(
                    text = "DigiLocker DID Wallet",
                    fontSize = 18.sp,
                    fontWeight = FontWeight.Bold,
                    color = Color(0xFF00B0FF)
                )
                Text(
                    text = "W3C Verifiable Credentials • SD-JWT",
                    fontSize = 11.sp,
                    color = VectorZSubtext
                )
            }
