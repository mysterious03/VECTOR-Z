        Spacer(modifier = Modifier.height(16.dp))

        // DID Identity Card
        Card(
            colors = CardDefaults.cardColors(containerColor = VectorZDarkGray),
            shape = RoundedCornerShape(14.dp),
            modifier = Modifier.fillMaxWidth()
        ) {
            Column(modifier = Modifier.padding(16.dp)) {
                Text(text = "DID IDENTIFIER (STRONGBOX P-256)", fontSize = 10.sp, fontWeight = FontWeight.Black, color = VectorZCyan)
                Spacer(modifier = Modifier.height(4.dp))
                Text(text = "did:jwk:eyJjcnZCI6IlAtMjU2Iiwia2lkIjoi...", fontSize = 11.sp, color = Color.White)
                Spacer(modifier = Modifier.height(8.dp))
                Text(text = "Holder: Aarav Vikram Sharma", fontWeight = FontWeight.Bold, color = Color.White)
            }
        }

        Spacer(modifier = Modifier.height(16.dp))
        Text(text = "SELECTIVE DISCLOSURE (ZERO RAW LEAK)", fontSize = 11.sp, fontWeight = FontWeight.Black, color = VectorZSubtext)
        Spacer(modifier = Modifier.height(8.dp))

        // Selective Checkboxes
        Card(
            colors = CardDefaults.cardColors(containerColor = VectorZDarkGray),
            shape = RoundedCornerShape(12.dp),
            modifier = Modifier.fillMaxWidth()
        ) {
            Column(modifier = Modifier.padding(12.dp)) {
                Row(verticalAlignment = Alignment.CenterVertically) {
                    Checkbox(checked = isOver18Disclosed, onCheckedChange = { isOver18Disclosed = it })
                    Text(text = "Disclose Age Proof (Over 18 = YES)", color = Color.White, fontSize = 12.sp)
                }
                Row(verticalAlignment = Alignment.CenterVertically) {
                    Checkbox(checked = isFullNameDisclosed, onCheckedChange = { isFullNameDisclosed = it })
                    Text(text = "Disclose Legal Name (Aarav Sharma)", color = Color.White, fontSize = 12.sp)
                }
                Row(verticalAlignment = Alignment.CenterVertically) {
